"""Regenerate notebooks/hydraulic/kaggle_train_hydraulic.ipynb from the
current source tree. Sibling to build_kaggle_notebook.py (CWRU) -- same
snapshot-not-live-synced pattern: re-run + re-push
(scripts/14_hydraulic_kaggle_push.sh) any time hydraulic_fusion_ad/ or any
configs/hydraulic_*.yaml changes.

Trains + evaluates all FOUR per-component detectors (cooler/valve/pump/
accumulator) in one kernel run -- see notes/09_hydraulic_notes.md's
"Per-component redesign" section for why one config = one component
(requiring all four components healthy at once, the original design, left
only 20 of 2205 cycles usable).

The raw ZeMA hydraulic data comes from the public
`jjacostupa/condition-monitoring-of-hydraulic-systems` Kaggle dataset
(attached via kernel-metadata.json's dataset_sources), readable from
/kaggle/input/ even with the kernel's Internet setting off -- same reason
as the CWRU notebook (this account isn't phone-verified). Unlike CWRU's
.mat -> .npz conversion, no format conversion is needed here: the files are
already plain tab-separated .txt, just copied into the layout
hydraulic_fusion_ad.data.catalog expects. The exact mount path is found by
locating profile.txt under /kaggle/input rather than hardcoded -- confirmed
via `kaggle datasets files` (flat layout, matches configs/hydraulic_*.yaml's
filenames exactly) but kept dynamic since a dataset republish could still
reorganize it.

Stdlib only -- run with any Python 3: `python3 scripts/build_kaggle_notebook_hydraulic.py`
"""
import base64
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "notebooks" / "hydraulic" / "kaggle_train_hydraulic.ipynb"

SRC_FILES = [
    "src/hydraulic_fusion_ad/__init__.py",
    "src/hydraulic_fusion_ad/config.py",
    "src/hydraulic_fusion_ad/data/__init__.py",
    "src/hydraulic_fusion_ad/data/catalog.py",
    "src/hydraulic_fusion_ad/data/dataset.py",
    "src/hydraulic_fusion_ad/data/torch_dataset.py",
    "src/hydraulic_fusion_ad/features/__init__.py",
    "src/hydraulic_fusion_ad/features/normalize.py",
    "src/hydraulic_fusion_ad/models/__init__.py",
    "src/hydraulic_fusion_ad/models/fusion_autoencoder.py",
    "src/hydraulic_fusion_ad/train.py",
    "src/hydraulic_fusion_ad/evaluate.py",
    "src/hydraulic_fusion_ad/viz.py",
]
COMPONENTS = ["cooler", "valve", "pump", "accumulator"]
CONFIG_FILES = [f"configs/hydraulic_{name}.yaml" for name in COMPONENTS]


def md(*lines):
    return {"cell_type": "markdown", "metadata": {}, "source": [l + "\n" for l in lines[:-1]] + ([lines[-1]] if lines else [])}


def code(*lines):
    return {
        "cell_type": "code",
        "execution_count": None,
        "metadata": {},
        "outputs": [],
        "source": [l + "\n" for l in lines[:-1]] + ([lines[-1]] if lines else []),
    }


def encode_files(relpaths: list[str]) -> str:
    entries = []
    for rel in relpaths:
        content = (ROOT / rel).read_bytes()
        b64 = base64.b64encode(content).decode("ascii")
        entries.append(f"    {rel!r}: (\n        {b64!r}\n    ),")
    return "\n".join(entries)


def build_notebook() -> dict:
    cells = []

    cells.append(md(
        "# Hydraulic Sensor Fusion Anomaly Detection -- Kaggle test run (CPU, offline)",
        "",
        "Self-contained snapshot of `src/hydraulic_fusion_ad/` (regenerated by "
        "`scripts/build_kaggle_notebook_hydraulic.py` -- not live-synced, re-run "
        "that script and re-push if the source changes). Second, independent "
        "experiment alongside the CWRU vibration MVP in this same project -- see "
        "/HYDRAULIC_PLAN.md and notes/09_hydraulic_notes.md for the full design.",
        "",
        "No Internet needed -- the attached "
        "`jjacostupa/condition-monitoring-of-hydraulic-systems` input dataset is "
        "readable regardless of the kernel's Internet setting. CPU only, no GPU "
        "requested (matches the local machine this also needs to run on "
        "eventually).",
    ))

    cells.append(md("## 1. Reconstruct the `hydraulic_fusion_ad` package + config on disk"))
    cells.append(code(
        "import base64, pathlib",
        "",
        "WORKDIR = pathlib.Path('/kaggle/working')",
        "SRC_FILES = {",
        encode_files(SRC_FILES),
        "}",
        "for relpath, b64 in SRC_FILES.items():",
        "    p = WORKDIR / relpath",
        "    p.parent.mkdir(parents=True, exist_ok=True)",
        "    p.write_bytes(base64.b64decode(b64))",
        "print(f'wrote {len(SRC_FILES)} source files under {WORKDIR}/src')",
    ))
    cells.append(code(
        "CONFIG_FILES = {",
        encode_files(CONFIG_FILES),
        "}",
        "for relpath, b64 in CONFIG_FILES.items():",
        "    p = WORKDIR / relpath",
        "    p.parent.mkdir(parents=True, exist_ok=True)",
        "    p.write_bytes(base64.b64decode(b64))",
        "print(f'wrote {len(CONFIG_FILES)} config files')",
    ))

    cells.append(md(
        "## 2. Environment setup + confirm PyTorch",
        "Same subprocess-PYTHONPATH pattern as the CWRU notebook -- `!python` "
        "on the PATH isn't guaranteed to be this kernel's interpreter, so "
        "everything below invokes `{sys.executable}` explicitly.",
    ))
    cells.append(code(
        "import sys, os, subprocess",
        "sys.path.insert(0, str(WORKDIR / 'src'))",
        "os.environ['PYTHONPATH'] = str(WORKDIR / 'src')",
        "os.chdir(WORKDIR)",
        "PY = sys.executable",
        "import torch",
        "print('python:', PY)",
        "print('torch:', torch.__version__)",
        "print('cuda available:', torch.cuda.is_available(), '(CPU-only run, expected)')",
        "",
        "def run(*args):",
        "    subprocess.run([PY, *args], check=True)",
    ))

    cells.append(md(
        "## 3. Locate + inspect the attached hydraulic dataset",
        "Mount path not previously confirmed for this dataset (see "
        "HYDRAULIC_PLAN.md's 'Open item') -- search for `profile.txt` under "
        "`/kaggle/input` rather than assuming a path. Prints the raw unique "
        "value counts per profile column *before* running any validated "
        "loader code, so a wrong assumption about column order/meaning "
        "(documented in notes/09_hydraulic_notes.md section 1) is visible "
        "immediately rather than surfacing only as a downstream ValueError.",
    ))
    cells.append(code(
        "_candidates = list(pathlib.Path('/kaggle/input').rglob('profile.txt'))",
        "if not _candidates:",
        "    print('profile.txt not found under /kaggle/input. Contents:')",
        "    for p in sorted(pathlib.Path('/kaggle/input').rglob('*'))[:200]:",
        "        print(' ', p)",
        "    raise FileNotFoundError(",
        "        \"jjacostupa/condition-monitoring-of-hydraulic-systems not found -- \"",
        "        \"is it attached to this kernel? (see kernel-metadata.json's dataset_sources)\"",
        "    )",
        "HYD_ROOT = _candidates[0].parent",
        "print(f'HYD_ROOT = {HYD_ROOT}')",
        "print('Files found there:', sorted(p.name for p in HYD_ROOT.glob(\"*.txt\")))",
        "for doc_name in ('documentation.txt', 'description.txt'):",
        "    doc_path = HYD_ROOT / doc_name",
        "    if doc_path.exists():",
        "        print(f'--- {doc_name} ---')",
        "        print(doc_path.read_text(errors='replace')[:3000])",
    ))
    cells.append(code(
        "import numpy as np",
        "import yaml",
        "# data.sensor_groups/profile_columns/valid_values are identical across all",
        "# four configs (only target_component + paths differ) -- any one will do here.",
        "hyd_config = yaml.safe_load((WORKDIR / 'configs/hydraulic_cooler.yaml').read_text())",
        "profile_cols = hyd_config['data']['profile_columns']",
        "profile_preview = np.loadtxt(HYD_ROOT / 'profile.txt', dtype=int)",
        "print(f'profile.txt shape: {profile_preview.shape} (expect (n_cycles, {len(profile_cols)}))')",
        "for i, col in enumerate(profile_cols):",
        "    vals, counts = np.unique(profile_preview[:, i], return_counts=True)",
        "    print(f'  column {i} ({col}): ' + ', '.join(f'{v}={c}' for v, c in zip(vals, counts)))",
    ))

    cells.append(md(
        "## 4. Copy the raw sensor files into the layout the loader expects",
        "No format conversion needed (unlike CWRU's .mat -> .npz) -- these "
        "are already plain tab-separated .txt files, just copied by name "
        "into `data/hydraulic_raw/`.",
    ))
    cells.append(code(
        "import shutil",
        "",
        "RAW_DIR = WORKDIR / 'data' / 'hydraulic_raw'",
        "RAW_DIR.mkdir(parents=True, exist_ok=True)",
        "expected = hyd_config['data']['sensor_groups']",
        "expected_files = ['profile.txt'] + [",
        "    f'{sensor}.txt' for group in expected.values() for sensor in group['sensors']",
        "]",
        "missing = [f for f in expected_files if not (HYD_ROOT / f).exists()]",
        "if missing:",
        "    raise FileNotFoundError(",
        "        f'Expected files missing from {HYD_ROOT}: {missing}. '",
        "        f'Actually present: {sorted(p.name for p in HYD_ROOT.glob(\"*.txt\"))}. '",
        "        'The assumed filenames in configs/hydraulic_*.yaml may not match this '",
        "        'copy of the dataset -- see notes/09_hydraulic_notes.md section 1.'",
        "    )",
        "for f in expected_files:",
        "    shutil.copy(HYD_ROOT / f, RAW_DIR / f)",
        "print(f'copied {len(expected_files)} files into {RAW_DIR}')",
    ))

    cells.append(md(
        "## 5. Train + evaluate all four per-component detectors",
        "One fusion autoencoder per component (cooler/valve/pump/"
        "accumulator), each trained only on cycles where THAT component is "
        "healthy (the other three are ignored -- see "
        "notes/09_hydraulic_notes.md's 'Per-component redesign' section for "
        "why: requiring all four healthy at once left only 20 of 2205 "
        "cycles usable). Three encoder branches (slow/medium/fast rate "
        "groups) fused at one bottleneck per detector -- see "
        "notes/09_hydraulic_notes.md section 3. Runs sequentially, CPU-only "
        "-- expect this to take a while.",
    ))
    cells.append(code(
        "import json",
        f"COMPONENTS = {COMPONENTS!r}",
        "all_metrics = {}",
        "for name in COMPONENTS:",
        "    config_path = f'configs/hydraulic_{name}.yaml'",
        "    print(f'=== {name} ({config_path}) ===')",
        "    run('-m', 'hydraulic_fusion_ad.train', '--config', config_path)",
        "    run('-m', 'hydraulic_fusion_ad.evaluate', '--config', config_path)",
        "    metrics_path = WORKDIR / f'outputs/hydraulic_reports/{name}/evaluation_metrics.json'",
        "    all_metrics[name] = json.loads(metrics_path.read_text())",
    ))

    cells.append(md("## 6. Metrics summary, all four detectors"))
    cells.append(code(
        "import json",
        "for name, m in all_metrics.items():",
        "    print(f\"{name:12s}  roc_auc={m['roc_auc']:.3f}  pr_auc={m['pr_auc']:.3f}  \"",
        "          f\"f1={m['f1']:.3f}  precision={m['precision']:.3f}  recall={m['recall']:.3f}  \"",
        "          f\"(n_val_healthy={m['n_val_healthy']}, n_test_healthy={m['n_test_healthy']}, \"",
        "          f\"n_test_degraded={m['n_test_degraded']})\")",
        "print()",
        "print(json.dumps(all_metrics, indent=2))",
    ))

    cells.append(md("## 7. Look at the results, per component"))
    cells.append(code(
        "from IPython.display import Image, display",
        "for name in COMPONENTS:",
        "    print(f'=== {name} ===')",
        "    figdir = WORKDIR / 'outputs' / 'hydraulic_figures' / name",
        "    for fname in ['error_histogram.png', 'roc_curve.png', 'confusion_matrix.png',",
        "                  'detection_rate_by_component_severity.png', 'branch_error_by_component.png']:",
        "        path = figdir / fname",
        "        if path.exists():",
        "            print(fname)",
        "            display(Image(filename=str(path)))",
    ))

    return {
        "cells": cells,
        "metadata": {
            "kernelspec": {"display_name": "Python 3", "language": "python", "name": "python3"},
            "language_info": {"name": "python", "version": "3.10"},
            "accelerator": "GPU",
        },
        "nbformat": 4,
        "nbformat_minor": 5,
    }


if __name__ == "__main__":
    notebook = build_notebook()
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(json.dumps(notebook, indent=1))
    print(f"wrote {OUT} ({OUT.stat().st_size} bytes, {len(notebook['cells'])} cells)")
