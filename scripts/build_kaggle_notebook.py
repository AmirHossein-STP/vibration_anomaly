"""Regenerate notebooks/kaggle_train.ipynb from the current source tree.

The Kaggle notebook is a SNAPSHOT, not live-synced: it embeds the current
contents of src/vibration_ad/, configs/default.yaml, and
data/raw/MANIFEST.txt as base64 (decoded back into real files by the
notebook's first cell when run on Kaggle). Re-run this script and re-push
(scripts/05_kaggle_push.sh) any time the package/config code changes.

The raw CWRU data comes from the public `esraakhaled299/cwru-data` Kaggle
dataset (attached via kernel-metadata.json's dataset_sources), converted
from its .mat format into the .npz format/naming convention the rest of
this pipeline expects (see the conversion cell below). Deliberately NOT a
runtime download from GitHub: attached input datasets are readable from
/kaggle/input/ even with the kernel's Internet setting off, which matters
because this Kaggle account isn't phone-verified -- see
notes/07_dvc_and_kaggle.md for the full story, including why uploading our
own copy of the data (the first workaround tried) doesn't work from this
machine either (an unrelated Google Cloud Storage geo-block).

Stdlib only -- run with any Python 3: `python3 scripts/build_kaggle_notebook.py`
"""
import base64
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "notebooks" / "kaggle_train.ipynb"

SRC_FILES = [
    "src/vibration_ad/__init__.py",
    "src/vibration_ad/config.py",
    "src/vibration_ad/data/__init__.py",
    "src/vibration_ad/data/catalog.py",
    "src/vibration_ad/data/dataset.py",
    "src/vibration_ad/data/download.py",
    "src/vibration_ad/data/torch_dataset.py",
    "src/vibration_ad/data/windows.py",
    "src/vibration_ad/features/__init__.py",
    "src/vibration_ad/features/spectrogram.py",
    "src/vibration_ad/models/__init__.py",
    "src/vibration_ad/models/autoencoder.py",
    "src/vibration_ad/train.py",
    "src/vibration_ad/evaluate.py",
    "src/vibration_ad/infer.py",
    "src/vibration_ad/viz.py",
]
CONFIG_FILES = [
    "configs/default.yaml",
    "data/raw/MANIFEST.txt",
]


def md(*lines):
    return {"cell_type": "markdown", "metadata": {}, "source": [l + "\n" for l in lines[:-1]] + ([lines[-1]] if lines else [])}


def code(*lines):
    return {
        "cell_type": "code",
        "execution_count": None,
        "metadata": {},
        "outputs": [],
        "source": [l + "\n" for l in lines[:-1]] + ([lines[-1]] if lines else []),
    }


def encode_files(relpaths: list[str]) -> str:
    entries = []
    for rel in relpaths:
        content = (ROOT / rel).read_bytes()
        b64 = base64.b64encode(content).decode("ascii")
        entries.append(f"    {rel!r}: (\n        {b64!r}\n    ),")
    return "\n".join(entries)


def build_notebook() -> dict:
    cells = []

    cells.append(md(
        "# Vibration Anomaly Detection -- Kaggle test run (CPU, offline)",
        "",
        "Self-contained snapshot of the `vibration_anomaly_detection` project "
        "(regenerated by `scripts/build_kaggle_notebook.py` -- not live-synced, "
        "re-run that script and re-push if the source changes). Reconstructs "
        "the `vibration_ad` package on disk from embedded source, converts the "
        "CWRU 12kHz Drive-End + Normal-baseline data from the attached "
        "`esraakhaled299/cwru-data` input dataset (.mat -> our .npz "
        "convention), then runs the full train -> evaluate -> infer pipeline "
        "on CPU.",
        "",
        "No Internet needed -- the attached input dataset is readable "
        "regardless of the kernel's Internet setting (this Kaggle account "
        "isn't phone-verified, which disables Internet/GPU in kernels "
        "outright; see notes/07_dvc_and_kaggle.md). GPU is deliberately not "
        "requested either -- CPU is fine, matching the local machine this "
        "also needs to run on eventually.",
        "",
        "See the parent project's `notes/` for why the pipeline is built this "
        "way (STFT choice, split strategy, threshold selection, etc.) -- this "
        "notebook is deliberately just the runner, not re-documented here.",
    ))

    cells.append(md("## 1. Reconstruct the `vibration_ad` package + config on disk"))

    cells.append(code(
        "import base64, pathlib",
        "",
        "WORKDIR = pathlib.Path('/kaggle/working')",
        "SRC_FILES = {",
        encode_files(SRC_FILES),
        "}",
        "for relpath, b64 in SRC_FILES.items():",
        "    p = WORKDIR / relpath",
        "    p.parent.mkdir(parents=True, exist_ok=True)",
        "    p.write_bytes(base64.b64decode(b64))",
        "print(f'wrote {len(SRC_FILES)} source files under {WORKDIR}/src')",
    ))

    cells.append(code(
        "CONFIG_FILES = {",
        encode_files(CONFIG_FILES),
        "}",
        "for relpath, b64 in CONFIG_FILES.items():",
        "    p = WORKDIR / relpath",
        "    p.parent.mkdir(parents=True, exist_ok=True)",
        "    p.write_bytes(base64.b64decode(b64))",
        "print(f'wrote {len(CONFIG_FILES)} config/manifest files')",
    ))

    cells.append(md(
        "## 2. Environment setup + confirm PyTorch",
        "",
        "The `!python -m ...` calls below run in a **separate shell subprocess**"
        " -- `sys.path.insert()` in this process doesn't reach them, and plain"
        " `python` on the PATH is not guaranteed to be the same interpreter as"
        " this notebook kernel (it can resolve to a bare system Python without"
        " torch/numpy/etc installed). So: set `PYTHONPATH` via `os.environ`"
        " (subprocesses inherit that) and always invoke `{sys.executable}`"
        " explicitly (guaranteed to be *this* kernel's interpreter) rather than"
        " bare `python`.",
    ))

    cells.append(code(
        "import sys, os, subprocess",
        "sys.path.insert(0, str(WORKDIR / 'src'))",
        "os.environ['PYTHONPATH'] = str(WORKDIR / 'src')",
        "os.chdir(WORKDIR)",
        "PY = sys.executable",
        "try:",
        "    import yaml  # noqa -- already on Kaggle's base image in practice",
        "except ImportError:",
        "    # best-effort: this needs internet, which may not be available",
        "    # (see the markdown above) -- if it's already installed, this",
        "    # branch never runs and nothing depends on internet access.",
        "    subprocess.run([PY, '-m', 'pip', 'install', '-q', 'pyyaml'])",
        "",
        "import torch",
        "print('python:', PY)",
        "print('torch:', torch.__version__)",
        "print('cuda available:', torch.cuda.is_available(), '(CPU-only run, expected)')",
    ))

    cells.append(code(
        "def run(*args):",
        "    # check=True -> raises (and stops the notebook) on a non-zero exit,",
        "    # instead of silently continuing to the next cell like `!` would.",
        "    subprocess.run([PY, *args], check=True)",
    ))

    cells.append(md(
        "## 3. Convert the CWRU dataset from the attached input (.mat -> .npz)",
        "`esraakhaled299/cwru-data` mirrors the same 64 files (12kHz "
        "Drive-End fault files + Normal baseline, all 4 RPM/load conditions) "
        "as `data/raw/MANIFEST.txt`, just as `.mat` instead of `.npz` and "
        "organized into folders instead of RPM-prefixed filenames. Original "
        "CWRU `.mat` files use a numeric-ID key prefix that varies per file "
        "(e.g. `X100_DE_time`, `X285_DE_time`) -- match by suffix "
        "(`_DE_time`) rather than hardcoding the ID. Mount path confirmed by "
        "a throwaway diagnostic kernel first "
        "(`notebooks/inspect_kernel/`) rather than assumed.",
    ))
    cells.append(code(
        "import scipy.io, re",
        "import numpy as np",
        "",
        "# Mount path for attached input datasets has proven inconsistent across",
        "# kernels in practice (confirmed .../datasets/<owner>/<slug>/... via a",
        "# diagnostic kernel, then a real run still didn't find it there) --",
        "# search for the known folder name instead of hardcoding a path.",
        "_candidates = list(pathlib.Path('/kaggle/input').rglob('CWRU_organized'))",
        "if not _candidates:",
        "    print('CWRU_organized not found under /kaggle/input. Contents:')",
        "    for p in sorted(pathlib.Path('/kaggle/input').rglob('*')):",
        "        print(' ', p)",
        "    raise FileNotFoundError(",
        "        \"cwru-data dataset not found under /kaggle/input -- is \"",
        "        \"'esraakhaled299/cwru-data' attached to this kernel? (see \"",
        "        \"kernel-metadata.json's dataset_sources)\"",
        "    )",
        "MAT_ROOT = _candidates[0]",
        "print(f'MAT_ROOT = {MAT_ROOT}')",
        "RAW_DIR = WORKDIR / 'data' / 'raw'",
        "RAW_DIR.mkdir(parents=True, exist_ok=True)",
        "LOAD_TO_RPM = {0: 1797, 1: 1772, 2: 1750, 3: 1730}",
        "",
        "BALL_IR_RE = re.compile(r'^(B|IR)(\\d{3})_(\\d)\\.mat$')",
        "OR_RE = re.compile(r'^OR(\\d{3})@(\\d+)_(\\d)\\.mat$')",
        "NORMAL_RE = re.compile(r'^Normal_(\\d)\\.mat$')",
        "",
        "def de_signal(mat_path):",
        "    d = scipy.io.loadmat(str(mat_path))",
        "    key = next(k for k in d if k.endswith('_DE_time'))",
        "    return d[key].ravel()",
        "",
        "n = 0",
        "for mat_path in sorted((MAT_ROOT / '12k_DE').rglob('*.mat')):",
        "    fname = mat_path.name",
        "    m = BALL_IR_RE.match(fname)",
        "    if m:",
        "        fault, size, load = m.group(1), int(m.group(2)), int(m.group(3))",
        "        out_name = f'{LOAD_TO_RPM[load]}_{fault}_{size}_DE12.npz'",
        "    else:",
        "        m = OR_RE.match(fname)",
        "        if not m:",
        "            print(f'skip (unrecognized): {mat_path}')",
        "            continue",
        "        size, pos, load = int(m.group(1)), m.group(2), int(m.group(3))",
        "        out_name = f'{LOAD_TO_RPM[load]}_OR@{pos}_{size}_DE12.npz'",
        "    np.savez(RAW_DIR / out_name, DE=de_signal(mat_path))",
        "    n += 1",
        "",
        "for mat_path in sorted((MAT_ROOT / 'Normal').rglob('*.mat')):",
        "    m = NORMAL_RE.match(mat_path.name)",
        "    if not m:",
        "        print(f'skip (unrecognized): {mat_path}')",
        "        continue",
        "    rpm = LOAD_TO_RPM[int(m.group(1))]",
        "    np.savez(RAW_DIR / f'{rpm}_Normal.npz', DE=de_signal(mat_path))",
        "    n += 1",
        "",
        "print(f'converted {n} files into {RAW_DIR}')",
        "assert n == 64, f'expected 64 files (matching data/raw/MANIFEST.txt), got {n}'",
    ))

    cells.append(md(
        "## 4. Train the autoencoder",
        "Healthy-only spectrograms, early-stopped on held-out healthy validation "
        "loss. Runs on CPU (see device print above) -- this is a small model "
        "(~a few hundred thousand params) on ~2800 training windows, so it's "
        "slow-ish but not impractical on CPU.",
    ))
    cells.append(code("run('-m', 'vibration_ad.train', '--config', 'configs/default.yaml')"))

    cells.append(md("## 5. Evaluate: reconstruction error -> anomaly detection, scored against CWRU's true fault labels"))
    cells.append(code("run('-m', 'vibration_ad.evaluate', '--config', 'configs/default.yaml')"))

    cells.append(code(
        "import json",
        "print(json.dumps(json.loads((WORKDIR / 'outputs/reports/evaluation_metrics.json').read_text()), indent=2))",
    ))

    cells.append(md("## 6. Demo inference on one healthy and one faulty file"))
    cells.append(code(
        "run('-m', 'vibration_ad.infer', '--config', 'configs/default.yaml', '--input', 'data/raw/1797_IR_21_DE12.npz')",
        "run('-m', 'vibration_ad.infer', '--config', 'configs/default.yaml', '--input', 'data/raw/1797_Normal.npz')",
    ))

    cells.append(md("## 7. Look at the results"))
    cells.append(code(
        "from IPython.display import Image, display",
        "figdir = WORKDIR / 'outputs' / 'figures'",
        "for name in ['error_histogram.png', 'roc_curve.png', 'detection_rate_by_severity.png',",
        "             'reconstruction_examples.png', 'infer_1797_IR_21_DE12_timeline.png',",
        "             'infer_1797_Normal_timeline.png']:",
        "    path = figdir / name",
        "    if path.exists():",
        "        print(name)",
        "        display(Image(filename=str(path)))",
    ))

    return {
        "cells": cells,
        "metadata": {
            "kernelspec": {"display_name": "Python 3", "language": "python", "name": "python3"},
            "language_info": {"name": "python", "version": "3.10"},
            "accelerator": "GPU",
        },
        "nbformat": 4,
        "nbformat_minor": 5,
    }


if __name__ == "__main__":
    notebook = build_notebook()
    OUT.write_text(json.dumps(notebook, indent=1))
    print(f"wrote {OUT} ({OUT.stat().st_size} bytes, {len(notebook['cells'])} cells)")
