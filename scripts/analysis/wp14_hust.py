"""WP14: HUST, five bearing types (notes/24, pre-registered).

Usage (box): python scripts/analysis/v2_cache.py --set cpw --datasets hust
             python scripts/analysis/v2_cache.py --set geofree --datasets hust
             python scripts/analysis/wp14_hust.py
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

import numpy as np
import pandas as pd
from sklearn.metrics import roc_auc_score

sys.path.insert(0, "src")
sys.path.insert(0, str(Path(__file__).parent))
from domain_adaptation.data.public_datasets import LABEL_NAMES, RACE_INVOLVING
from domain_adaptation.features.geofree import BIN_NAMES
from domain_adaptation.method import LINES, fit_baseline
from v2_cache import load_v2

DETECTORS = {"six_line": LINES, "geometry_free": BIN_NAMES}


def run(frames: dict[str, pd.DataFrame]) -> dict:
    out = {}
    for det, cols in DETECTORS.items():
        df = frames[det]
        per_type = {}
        for btype in sorted(df.unit.unique()):
            t = df[df.unit == btype]
            rows = []
            for load in sorted(t.condition.unique()):
                h = t[t.label == 0]
                cal, held = h[h.condition != load], h[h.condition == load]
                fault = t[(t.label > 0) & (t.condition == load)]
                b = fit_baseline(cal[cols].to_numpy(), cal.recording.to_numpy())
                thr = b.threshold()
                sh, sf = b.score(held[cols].to_numpy()), b.score(fault[cols].to_numpy())
                race = fault.label.isin(RACE_INVOLVING).to_numpy()
                r = {"load": load, "fa": float((sh > thr).mean()), "recall_race": float((sf[race] > thr).mean()),
                     "auc_race": float(roc_auc_score(np.r_[np.zeros(len(sh)), np.ones(race.sum())], np.r_[sh, sf[race]]))}
                for lab in sorted(fault.label.unique()):
                    r[f"recall_{LABEL_NAMES[lab]}"] = float((sf[fault.label.to_numpy() == lab] > thr).mean())
                if det == "six_line":
                    io = fault[fault.label.isin((1, 2))]
                    if len(io):
                        r["typing_hits"] = int((b.typing(io[LINES].to_numpy()) == io.label.to_numpy()).sum())
                        r["typing_n"] = int(len(io))
                rows.append(r)
            p = pd.DataFrame(rows)
            per_type[str(btype)] = {"auc_race": p.auc_race.mean(), "auc_race_min": p.auc_race.min(), "fa": p.fa.mean(),
                               "fa_worst": p.fa.max(), "recall_race": p.recall_race.mean(),
                               **{c: p[c].mean() for c in p.columns if c.startswith("recall_") and c != "recall_race"},
                               **({"typing": p.typing_hits.sum() / p.typing_n.sum()} if "typing_hits" in p else {}),
                               "folds": rows}
        out[det] = per_type
    return out


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", type=Path, default=Path("outputs/wp14"))
    a = ap.parse_args()
    frames = {"six_line": load_v2("hust", fset="cpw"), "geometry_free": load_v2("hust", fset="geofree")}
    res = run(frames)
    six, geo = res["six_line"], res["geometry_free"]
    types = sorted(six)
    gate_types = [t for t in types if six[t]["auc_race"] >= 0.80]
    hits = sum(f.get("typing_hits", 0) for t in types for f in six[t]["folds"])
    n = sum(f.get("typing_n", 0) for t in types for f in six[t]["folds"])
    typing = hits / n
    gate = len(gate_types) >= 4 and typing > 0.6
    geo_wins = (sum(geo[t]["auc_race"] >= six[t]["auc_race"] for t in types) >= 4
                and float(np.mean([geo[t]["fa"] for t in types])) <= 0.15)

    L = ["# WP14: HUST, five bearing types (unseen)", "",
         "Generated by `scripts/analysis/wp14_hust.py`; pre-registered in notes/24. Baseline = same type's healthy "
         "files at the other two loads (cross-fitted); held-out healthy and faults at the third load; alpha 0.10.", "",
         f"**Many-bearings gate: {'PASS' if gate else 'FAIL'}** -- six-line race AUC >= 0.80 on {len(gate_types)}/5 types "
         f"({gate_types}); typing {typing:.3f} over {n} I/O windows (needs > 0.6).",
         f"**Head to head: geometry-free {'WINS' if geo_wins else 'does not win'} HUST** (AUC >= six-line on "
         f"{sum(geo[t]['auc_race'] >= six[t]['auc_race'] for t in types)}/5 types; mean FA {np.mean([geo[t]['fa'] for t in types]):.3f}).", "",
         "| type | detector | race AUC (worst load) | race recall | FA (worst) | typing | per type recall |", "|---|---|---|---|---|---|---|"]
    for t in types:
        for det, r in (("six-line", six[t]), ("geometry-free", geo[t])):
            per = ", ".join(f"{k[7:]} {v:.2f}" for k, v in r.items() if k.startswith("recall_") and k != "recall_race")
            L.append(f"| {t} | {det} | {r['auc_race']:.3f} ({r['auc_race_min']:.2f}) | {r['recall_race']:.3f} | "
                     f"{r['fa']:.3f} ({r['fa_worst']:.2f}) | {r.get('typing', float('nan')):.2f} | {per} |")
    md = "\n".join(L) + "\n"
    a.out.mkdir(parents=True, exist_ok=True)
    (a.out / "wp14_report.md").write_text(md)
    (a.out / "wp14_results.json").write_text(json.dumps({"gate": gate, "geo_wins": geo_wins, "typing": typing,
                                                          "results": res}, indent=1, default=float))
    print(md)


if __name__ == "__main__":
    main()
