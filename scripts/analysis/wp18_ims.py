"""WP18: the IMS final exam through the FROZEN bearing service (notes/27, pre-registered).

Run ONLY after the freeze is recorded in notes/22 §8 and IMS has been unsealed with
    python -I remote/datasets/fetch.py unseal ims --commit <frozen sha> --confirm WP11
(which extracts IMS.zip to ~/work/scratch/ims_unsealed). This script then extracts the
per-test .rar archives there, converts records to .npy service inputs, and drives
`python -m serving_core bearing` (calibrate -> promote -> infer) exactly as an operator would.

Usage (box): python scripts/analysis/wp18_ims.py
"""
from __future__ import annotations

import argparse
import csv
import json
import re
import subprocess
import sys
from concurrent.futures import ProcessPoolExecutor
from pathlib import Path

import numpy as np

sys.path.insert(0, "remote/datasets")
from safe_extract import extract_rar

UNSEALED = Path.home() / "work/scratch/ims_unsealed"
SERVICE = Path.home() / "work/scratch/ims_service"
STAMP = re.compile(r"^\d{4}\.\d{2}\.\d{2}\.\d{2}\.\d{2}\.\d{2}$")
TESTS = {"2003.10": 1, "2004.02": 2, "2004.03": 3}           # first-record month -> test number
FAILED = {(1, 3): "inner race", (1, 4): "roller", (2, 1): "outer race", (3, 3): "outer race"}
BASE_N = 200
CONFIG = ('fs_hz: 20000\nrpm: 2000\nbearing: {designation: "Rexnord ZA-2115"}\n'
          'default_unit: unused\ndetector: {detector}\n')
# notes/27 §2: geometry-free became primary at WP15, so it is the primary run; six-line is reported alongside
DETECTORS = ("geometry_free", "six_line")


def find_tests() -> dict[int, Path]:
    for rar in sorted(UNSEALED.rglob("*.rar")):
        if "__MACOSX" in rar.parts or rar.name.startswith("._"):     # AppleDouble metadata in the zip, not data
            continue
        dest = UNSEALED / "rar" / rar.stem
        if not dest.exists():
            extract_rar(rar, dest)
    out = {}
    for d in {p.parent for p in UNSEALED.rglob("*") if p.is_file() and STAMP.match(p.name) and "__MACOSX" not in p.parts}:
        first = sorted(p.name for p in d.iterdir() if STAMP.match(p.name))[0]
        out[TESTS[first[:7]]] = d
    if sorted(out) != [1, 2, 3]:
        raise SystemExit(f"expected tests 1-3, found {sorted(out)} in {UNSEALED}")
    return out


def _convert(args):
    src, dst, col = args
    a = np.loadtxt(src)
    np.save(dst, a[:, col].astype(np.float64))


def build(tests: dict[int, Path], jobs: int) -> list[str]:
    data = SERVICE / "geometry_free" / "data" / "bearing"
    work, units = [], []
    for t, d in sorted(tests.items()):
        files = sorted(p for p in d.iterdir() if STAMP.match(p.name))
        n_ch = np.loadtxt(files[0]).shape[1]
        for b in range(1, 5):
            col = 2 * (b - 1) if n_ch == 8 else b - 1          # test 1: x channel of each bearing pair
            unit = f"t{t}_b{b}"
            units.append(unit)
            for k, f in enumerate(files):
                sub = "train" if k < BASE_N else "in"
                (data / sub / unit).mkdir(parents=True, exist_ok=True)
                work.append((f, data / sub / unit / f"{f.name}.npy", col))
    with ProcessPoolExecutor(jobs) as ex:
        list(ex.map(_convert, work, chunksize=64))
    for det in DETECTORS:          # same input files (hard links), one service root per detector
        root = SERVICE / det / "data" / "bearing"
        if det != "geometry_free" and not root.exists():
            root.parent.mkdir(parents=True, exist_ok=True)
            subprocess.run(["cp", "-al", str(data), str(root)], check=True)
        (root / "config").mkdir(parents=True, exist_ok=True)
        (root / "config" / "service.yaml").write_text(CONFIG.replace("{detector}", det))
    return units


def cli(det: str, *args) -> str:
    r = subprocess.run([sys.executable, "-m", "serving_core", "bearing", "--data-root", str(SERVICE / det / "data"),
                        "--models-root", str(SERVICE / det / "models"), *args], capture_output=True, text=True,
                       env={"PYTHONPATH": "src", "PATH": "/usr/bin:/bin"})
    if r.returncode not in (0, 1):
        raise SystemExit(f"service {args} failed ({r.returncode}): {r.stderr[-2000:]}")
    return r.stdout


def score(det: str, units: list[str]):
    out = cli(det, "calibrate")
    version = out.split("Candidate model:")[1].split()[0]
    cli(det, "promote", version, "--yes")
    cli(det, "infer")
    job = sorted((SERVICE / det / "data" / "bearing" / "out").glob("*/infer-*"))[-1]
    rows = json.loads((job / "results.json").read_text())["rows"]
    with (SERVICE / det / "data" / "bearing" / "out" / "bearing_trend.csv").open() as f:
        trend = list(csv.DictReader(f))

    res, L = {}, [f"## detector: {det}{' (primary, v1.1)' if det == 'geometry_free' else ' (v1.0 detector, alongside)'}", "",
                  f"Generated by `scripts/analysis/wp18_ims.py`; pre-registered in notes/27. Model {version}; baseline "
                  f"= first {BASE_N} records per unit; 2000 rpm; Rexnord ZA-2115.", "",
                  "| unit | documented | records | first trend alarm (h after baseline) | lead to end (h) | first faulty (h) | "
                  "faulty share | trend events/day (before last 10%) | typed at end |", "|---|---|---|---|---|---|---|---|---|"]
    for u in units:
        t, b = int(u[1]), int(u[-1])
        r = [x for x in rows if x.get("unit") == u and x.get("status") == "ok"]
        tr = [x for x in trend if x["unit"] == u]
        n = len(r)
        hours = lambda i: i * 10 / 60      # records are 10 min apart (test 1 starts at 5 min: approximation)
        alarm = [x["trend_alarm"] == "True" for x in tr]
        first_alarm = next((i for i, v in enumerate(alarm) if v), None)
        first_faulty = next((i for i, x in enumerate(r) if x["verdict"] == "faulty"), None)
        cut = int(0.9 * n)
        events = sum(1 for i in range(1, cut) if alarm[i] and not alarm[i - 1]) + (1 if cut and alarm[0] else 0)
        tail = [x["fault_type"] for x in r[cut:] if x["fault_type"]]
        typed = max(set(tail), key=tail.count) if tail else ""
        res[u] = {"documented": FAILED.get((t, b), "none"), "n": n,
                  "first_alarm_h": hours(first_alarm) if first_alarm is not None else None,
                  "lead_h": hours(n - first_alarm) if first_alarm is not None else None,
                  "first_faulty_h": hours(first_faulty) if first_faulty is not None else None,
                  "faulty_share": float(np.mean([x["verdict"] == "faulty" for x in r])) if r else None,
                  "events_per_day": events / (hours(cut) / 24) if cut else None, "typed": typed}
        x = res[u]
        f = lambda v, d=1: "—" if v is None else f"{v:.{d}f}"
        L.append(f"| {u} | {x['documented']} | {n} | {f(x['first_alarm_h'])} | {f(x['lead_h'])} | {f(x['first_faulty_h'])} | "
                 f"{f(x['faulty_share'], 2)} | {f(x['events_per_day'], 2)} | {typed} |")
    failing = [u for u in units if (int(u[1]), int(u[-1])) in FAILED]
    race = [u for u in failing if FAILED[(int(u[1]), int(u[-1]))] != "roller"]
    healthy = [u for u in units if u not in failing]
    c1 = sum(res[u]["first_alarm_h"] is not None for u in failing)
    c2 = sum(res[u]["typed"] == FAILED[(int(u[1]), int(u[-1]))] for u in race)
    c3 = float(np.mean([res[u]["events_per_day"] for u in healthy]))
    consistent = c1 >= 3 and c2 >= 2 and c3 <= 1.0
    res["_readings"] = {"c1": c1, "c2": c2, "c3": c3, "consistent": consistent, "model": version}
    L += ["", f"**Pre-registered readings (notes/27 §3):** trend alarm before end on {c1}/4 failing units (need >= 3); "
              f"typing right on {c2}/3 race failures (need >= 2); non-failing units {c3:.2f} trend events/day (need <= 1) "
              f"-> **{'CONSISTENT with development' if consistent else 'NOT consistent with development'}**."]
    return res, L, consistent


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--jobs", type=int, default=8)
    ap.add_argument("--out", type=Path, default=Path("outputs/wp18"))
    a = ap.parse_args()
    tests = find_tests()
    units = build(tests, a.jobs)
    L, allres = ["# WP18: IMS final exam through the frozen bearing service", ""], {}
    for det in DETECTORS:
        res, Ld, verdict = score(det, units)
        allres[det] = res
        L += Ld + [""]
    md = "\n".join(L) + "\n"
    a.out.mkdir(parents=True, exist_ok=True)
    (a.out / "wp18_report.md").write_text(md)
    (a.out / "wp18_results.json").write_text(json.dumps(allres, indent=1, default=float))
    print(md)


if __name__ == "__main__":
    main()
