"""MASTER_PLAN.md WP2: why does the envelope model fail at 1500 rpm?

H-a is settled (notes/14 §4): every 1500 rpm condition is bad, so the
cause is speed. This script compares the feature variants that test the
remaining mechanisms, all defined in envelope_cache.VARIANTS before any of
them was run:

    hb_revs15   H-b  windows of 15 shaft revolutions (same order resolution at every speed)
    hb_median   H-b  peak / median normalisation instead of peak / sum
    hc_reltol5  H-c  +-5% relative order tolerance instead of +-0.08 absolute
    hd_cpw_ses  H-d  cepstrum pre-whitening + squared envelope, no band chosen

Same model and counting as WP1: CWRU-only logistic regression, threshold
from 5 healthy Paderborn units, false alarms on the 6th, 10% window target.

Pre-registered readings (written before the variants were extracted):
- The 1500 rpm gap is N09 recall minus the mean recall of the three N15
  conditions, at the 10% window point under leave-one-healthy-unit-out.
  For v1 it is 0.740 - mean(0.480, 0.289, 0.506) = 0.315.
- A variant EXPLAINS the drop if it closes at least half the gap (N15 mean
  recall up by >= 0.16) while N09 recall does not fall by more than 0.05
  and held-out FA stays within 0.03 of the target.
- If a variant closes the gap by lowering N09, it has equalised the speeds
  by degrading both. That is not an explanation.
- If none qualifies, H-b/H-c(nominal speed)/H-d are rejected as stated, and
  what remains is H-c with MEASURED speed (needs the PU speed channel,
  Kaggle re-extraction) or a physical limit, to be written up as such.
- Paderborn is a development target here. A variant that wins is adopted
  into feature set v2 (WP3) only if it also holds on leave-one-dataset-out
  (WP5) -- choosing a feature variant by Paderborn fault recall alone would
  be selection on target labels (§4 rule 4).

Usage: python scripts/analysis/wp2_n15.py [--variants v1 hb_revs15 ...]
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

import numpy as np

sys.path.insert(0, str(Path(__file__).parent))
from envelope_cache import VARIANTS, load_cache
from wp1_rescore import CONDITIONS, SERVICE_LEVELS, mean_sd, score_variant

N15 = [c for c in CONDITIONS if c.startswith("N15")]


def summarise(results: dict) -> dict:
    out = {}
    for c, r in results.items():
        w = r["window"]["0.10"]
        rec = r["recording"]["0.10"]
        faulty_key = min((k for k in rec if float(k) >= SERVICE_LEVELS["faulty"] - 1e-9), key=float)
        units = r["units"]["0.10"]["faulty_units_caught_fraction"]
        out[c] = {"recall": float(np.mean(w["lohuo_recall_real"])), "recall_sd": float(np.std(w["lohuo_recall_real"], ddof=1)),
                  "fa": float(np.mean(w["lohuo_fa"])), "fa_worst": float(max(w["lohuo_fa"])),
                  "recall_art": float(np.mean(w["lohuo_recall_artificial"])),
                  "rec_recall": float(np.mean(rec[faulty_key]["recall_real"])),
                  "rec_fa": float(np.mean(rec[faulty_key]["fa"])),
                  "units_caught": int(sum(v >= 0.5 for v in units.values())), "n_units": len(units)}
    return out


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--variants", nargs="*", default=list(VARIANTS))
    ap.add_argument("--cache", type=Path, default=Path("outputs/envelope_cache"))
    ap.add_argument("--out", type=Path, default=Path("outputs/wp2"))
    args = ap.parse_args()

    summary, drift_all = {}, {}
    for v in args.variants:
        try:
            df = load_cache(args.cache, v)
        except FileNotFoundError as e:
            print(f"[{v}] skipped: {e}")
            continue
        results, drift, _ = score_variant(df)
        summary[v] = summarise(results)
        drift_all[v] = {c: d.to_dict() for c, d in drift.items()}

    L = ["# WP2 results: the 1500 rpm drop, by feature variant", "",
         "Generated by `scripts/analysis/wp2_n15.py`. Real damage, 10% window target, threshold from 5 healthy "
         "units and FA on the 6th (mean over 6 folds). Recording columns use the service's faulty level (≥50% of windows).", "",
         "| variant | condition | window recall | held-out FA (worst) | artificial recall | recording recall | recording FA | units caught |",
         "|---|---|---|---|---|---|---|---|"]
    for v, sv in summary.items():
        for c, m in sv.items():
            L.append(f"| {v} | {c} | {m['recall']:.3f} ± {m['recall_sd']:.3f} | {m['fa']:.3f} ({m['fa_worst']:.2f}) | "
                     f"{m['recall_art']:.3f} | {m['rec_recall']:.3f} | {m['rec_fa']:.3f} | {m['units_caught']}/{m['n_units']} |")
    L += ["", "## Verdict against the pre-registered readings", "",
          "| variant | N09 recall | N15 mean recall | gap | N15 gain vs v1 | N09 change vs v1 | max FA deviation | explains? |",
          "|---|---|---|---|---|---|---|---|"]
    base = summary.get("v1")
    verdict = {}
    for v, sv in summary.items():
        n09, n15 = sv["N09_M07_F10"]["recall"], float(np.mean([sv[c]["recall"] for c in N15]))
        fadev = max(abs(m["fa"] - 0.10) for m in sv.values())
        if base and v != "v1":
            b09 = base["N09_M07_F10"]["recall"]; b15 = float(np.mean([base[c]["recall"] for c in N15]))
            gain, d09 = n15 - b15, n09 - b09
            ok = gain >= (b09 - b15) / 2 and d09 >= -0.05 and fadev <= 0.03
            verdict[v] = bool(ok)
            L.append(f"| {v} | {n09:.3f} | {n15:.3f} | {n09 - n15:.3f} | {gain:+.3f} | {d09:+.3f} | {fadev:.3f} | "
                     f"{'**yes**' if ok else 'no'} |")
        else:
            L.append(f"| {v} | {n09:.3f} | {n15:.3f} | {n09 - n15:.3f} | — | — | {fadev:.3f} | reference |")
    md = "\n".join(L) + "\n"
    args.out.mkdir(parents=True, exist_ok=True)
    (args.out / "wp2_report.md").write_text(md)
    (args.out / "wp2_results.json").write_text(json.dumps({"summary": summary, "verdict": verdict,
                                                          "drift": drift_all}, indent=1, default=float))
    print(md)


if __name__ == "__main__":
    main()
