"""MASTER_PLAN WP3: physics features v2 against the frozen arm d (notes/19).

Arms (all cross-fitted, conformal alpha 0.10, notes/17 folds):
  d_xf    frozen arm d (v1 lines, frozen caches)
  f1      family-mean over BPFO/BPFI x1-3 (v2 cache, new tolerance): the aggregation effect alone
  v2fam   family-mean z per family {outer, inner(+sidebands), ball, cage}, max over families (primary v2)
  v2max   max z over all 17 lines
Gate: notes/19 §3.

Usage: python scripts/analysis/wp3_score.py
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

import numpy as np
import pandas as pd

sys.path.insert(0, "src")
sys.path.insert(0, str(Path(__file__).parent))
from domain_adaptation.features.physics_v2 import FAMILIES, FAMILY_LABEL, V2_NAMES
from v2_cache import load_v2
from wp5_score import evaluate, load_frames, physics_xf

COL_FAMILY = {c: fam for fam, cols in FAMILIES.items() for c in cols}


def label_of(name: str) -> int:
    """Family name, or (for v2max's single-line 'families') the line's family -> label."""
    return FAMILY_LABEL[name] if name in FAMILY_LABEL else FAMILY_LABEL[COL_FAMILY[name]]


V1_FAMILIES = {"outer": ["bpfo_h1", "bpfo_h2", "bpfo_h3"], "inner": ["bpfi_h1", "bpfi_h2", "bpfi_h3"]}


def _groups(cal: pd.DataFrame) -> np.ndarray:
    if cal.recording.nunique() >= 2:
        return cal.recording.to_numpy()
    return np.minimum((np.argsort(np.argsort(cal.t0.to_numpy())) * 3) // len(cal), 2)


def family_scorer(families: dict[str, list[str]]):
    cols = [c for fam in families.values() for c in fam]
    idx = {f: [cols.index(c) for c in fam] for f, fam in families.items()}
    names = list(families)
    lg = lambda f: np.log(f[cols].to_numpy() + 1e-9)

    def fam_z(lz):
        return np.stack([lz[:, idx[f]].mean(1) for f in names], 1)

    def factory(cal: pd.DataFrame):
        lc = lg(cal)
        mu, sd = lc.mean(0), lc.std(0) + 1e-12
        score = lambda f: fam_z((lg(f) - mu) / sd).max(1)
        g, out = _groups(cal), np.empty(len(cal))
        for k in np.unique(g):
            m = g == k
            out[m] = fam_z((lc[m] - lc[~m].mean(0)) / (lc[~m].std(0) + 1e-12)).max(1)
        score.calibration = out

        def typer(fault: pd.DataFrame) -> dict:
            if fault.empty:
                return {}
            fz = fam_z((lg(fault) - mu) / sd)
            pred = np.array([label_of(names[i]) for i in fz.argmax(1)])
            lab = fault.label.to_numpy()
            res = {}
            race = np.isin(lab, (1, 2))
            if race.any():
                # race typing is between the two races only, as v1 (a ball/cage call counts as wrong)
                res["typing"] = float((pred[race] == lab[race]).mean())
            for code, nm in ((3, "ball"), (4, "cage")):
                if (lab == code).any() and any(label_of(n) == code for n in names):
                    res[f"typing_{nm}"] = float((pred[lab == code] == code).mean())
            return res
        return score, typer
    return factory


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", type=Path, default=Path("outputs/wp3"))
    args = ap.parse_args()
    frozen, _, _ = load_frames()
    v2 = {d: load_v2(d) for d in ("cwru", "pu", "ottawa_2018", "ottawa_2023", "mfpt")}
    arms = {"f1": family_scorer(V1_FAMILIES), "v2fam": family_scorer(FAMILIES),
            "v2max": family_scorer({c: [c] for c in V2_NAMES})}
    results = {}
    for name, (_, cpw) in frozen.items():
        frame = v2["pu"][v2["pu"].condition == name.split(":")[1]] if name.startswith("pu:") else v2[name]
        for b in (["machine", "own"] if name == "ottawa_2023" else ["machine"]):
            key = name if b == "machine" else f"{name}:own"
            results[key] = {"d_xf": evaluate(name, cpw, physics_xf, b, typing=True)}
            for arm, fac in arms.items():
                results[key][arm] = evaluate(name, frame, fac, b, typing=True)

    # gate (notes/19 §3)
    a_ok = {k: r["v2fam"]["summary"]["auc_race"] >= r["d_xf"]["summary"]["auc_race"] - 0.02 for k, r in results.items()}
    bc_sets = ["ottawa_2018", "ottawa_2023", "ottawa_2023:own"]
    bc_gain = {k: results[k]["v2fam"]["summary"].get("auc_bc", np.nan) - results[k]["d_xf"]["summary"].get("auc_bc", np.nan)
               for k in bc_sets}
    b_ok = sum(1 for v in bc_gain.values() if v >= 0.10) >= 2
    adopted = all(a_ok.values()) and b_ok

    L = ["# WP3 results: physics features v2 vs the frozen arm d", "",
         "Generated by `scripts/analysis/wp3_score.py`; pre-registered in notes/19. All arms cross-fitted, "
         "conformal alpha 0.10. AUC = held-out healthy vs faulty windows (race = inner+outer; b+c = ball+cage).", "",
         f"**Gate: v2fam {'ADOPTED' if adopted else 'NOT adopted (v1 stays)'}.** "
         f"(a) race AUC within 0.02 of d_xf everywhere: {all(a_ok.values())} "
         f"(fails: {[k for k, v in a_ok.items() if not v] or 'none'}); "
         f"(b) ball+cage AUC gain >= 0.10 on >= 2 of 3: {b_ok} ({ {k: round(v, 3) for k, v in bc_gain.items()} }).", "",
         "| dataset | arm | race AUC (worst) | race recall | FA (worst) | b+c AUC | ball / cage recall | typing race | typing ball / cage |",
         "|---|---|---|---|---|---|---|---|---|"]
    for key, rr in results.items():
        for arm, r in rr.items():
            s = r["summary"]
            f = lambda k, d=2: f"{s[k]:.{d}f}" if k in s and not np.isnan(s[k]) else "—"
            L.append(f"| {key} | {arm} | {f('auc_race', 3)} ({f('auc_race_min')}) | {f('recall_race', 3)} | "
                     f"{f('fa_mean', 3)} ({f('fa_worst')}) | {f('auc_bc', 3)} | {f('recall_ball')} / {f('recall_cage')} | "
                     f"{f('typing', 3)} | {f('typing_ball')} / {f('typing_cage')} |")
    md = "\n".join(L) + "\n"
    args.out.mkdir(parents=True, exist_ok=True)
    (args.out / "wp3_report.md").write_text(md)
    (args.out / "wp3_results.json").write_text(json.dumps(
        {"adopted": adopted, "a_ok": a_ok, "bc_gain": bc_gain, "results": results}, indent=1, default=float))
    print(md)


if __name__ == "__main__":
    main()
