"""WP13: the geometry-free score vs method v1.0 arm d (notes/23, pre-registered).

Usage (box): python scripts/analysis/v2_cache.py --set geofree --datasets cwru pu ottawa_2018 ottawa_2023 mfpt
             python scripts/analysis/wp13_geofree.py
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

import numpy as np

sys.path.insert(0, "src")
sys.path.insert(0, str(Path(__file__).parent))
from domain_adaptation.bearings import lookup
from domain_adaptation.features.geofree import BIN_CENTRES, BIN_NAMES
from domain_adaptation.method import default_groups, fit_baseline
from v2_cache import load_v2
from wp5_score import evaluate

GEOMETRY = {"cwru": "SKF 6205-2RS JEM", "pu": "6203 (Paderborn KAt)", "ottawa_2018": "ER16K",
            "ottawa_2023": "NSK 6203ZZ", "mfpt": "MFPT test bearing"}
ROWS = ["cwru", "pu:N09_M07_F10", "pu:N15 (worst)", "ottawa_2018", "ottawa_2023:own", "mfpt"]


def geofree_factory(dataset: str):
    g = lookup(GEOMETRY[dataset.split(":")[0]])
    true_orders = np.array([g.bpfo * h for h in (1, 2, 3)] + [g.bpfi * h for h in (1, 2, 3)])

    def factory(cal):
        b = fit_baseline(cal[BIN_NAMES].to_numpy(), default_groups(cal.recording.to_numpy(), cal.t0.to_numpy()))
        score = lambda f: b.score(f[BIN_NAMES].to_numpy())
        score.calibration = b.cal_scores

        def typer(fault):
            race = fault[fault.label.isin((1, 2))]
            if race.empty:
                return {}
            z = b.z(race[BIN_NAMES].to_numpy())
            over = z.max(1) > b.threshold()
            if not over.any():
                return {"typing_dominant_on_line": float("nan")}
            dom = BIN_CENTRES[z[over].argmax(1)]
            return {"typing_dominant_on_line": float((np.abs(dom[:, None] - true_orders[None, :]).min(1) <= 0.15).mean())}
        return score, typer
    return factory


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", type=Path, default=Path("outputs/wp13"))
    a = ap.parse_args()
    ref = json.loads(Path("outputs/wp5/wp5_results.json").read_text())["results"]
    res = {}
    for d in ("cwru", "pu", "ottawa_2018", "ottawa_2023", "mfpt"):
        df = load_v2(d, fset="geofree")
        parts = {f"pu:{c}": df[df.condition == c] for c in sorted(df.condition.unique())} if d == "pu" else {d: df}
        for name, frame in parts.items():
            for b in (["machine", "own"] if d == "ottawa_2023" else ["machine"]):
                key = name if b == "machine" else f"{name}:own"
                r = evaluate(name, frame, geofree_factory(name), b, typing=True)["summary"]
                res[key] = {"geofree": r, "d_xf_auc": ref[key]["d_xf"]["summary"]["auc_race"]}
    n15 = [k for k in res if k.startswith("pu:N15")]
    worst = min(n15, key=lambda k: res[k]["geofree"]["auc_race"])
    row_key = {"pu:N15 (worst)": worst}
    ok = {}
    for r in ROWS:
        k = row_key.get(r, r)
        ok[r] = res[k]["geofree"]["auc_race"] >= res[k]["d_xf_auc"] - 0.05
    ships = sum(ok.values()) >= 5

    L = ["# WP13: geometry-free score vs method v1.0 (arm d)", "",
         "Generated by `scripts/analysis/wp13_geofree.py`; pre-registered in notes/23. Cross-fitted, alpha 0.10, notes/17 folds.", "",
         f"**Gate: {'SHIPS as the unknown-geometry fallback' if ships else 'does NOT ship (fallback = level/kurtosis + warning)'}** "
         f"({sum(ok.values())}/6 rows within 0.05 of arm d; failing: {[r for r, v in ok.items() if not v] or 'none'}).", "",
         "| dataset | arm d AUC | geometry-free AUC | recall | FA (worst) | dominant order on a fault line |",
         "|---|---|---|---|---|---|"]
    for k, v in res.items():
        s = v["geofree"]
        L.append(f"| {k} | {v['d_xf_auc']:.3f} | {s['auc_race']:.3f} | {s['recall_race']:.3f} | "
                 f"{s['fa_mean']:.3f} ({s['fa_worst']:.2f}) | {s.get('typing_dominant_on_line', float('nan')):.2f} |")
    md = "\n".join(L) + "\n"
    a.out.mkdir(parents=True, exist_ok=True)
    (a.out / "wp13_report.md").write_text(md)
    (a.out / "wp13_results.json").write_text(json.dumps({"ships": ships, "rows_ok": ok, "results": res}, indent=1, default=float))
    print(md)


if __name__ == "__main__":
    main()
