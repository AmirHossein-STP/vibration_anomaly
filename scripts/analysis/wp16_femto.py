"""WP16: FEMTO/PRONOSTIA, long-baseline false alarms of the trigger (notes/26, pre-registered).

Reads the nested archives straight from the vault copy (member names checked,
nothing executed), computes per-record level/impulsiveness, then the CUSUM
analysis for each baseline length.

Usage (box): python scripts/analysis/wp16_femto.py
"""
from __future__ import annotations

import argparse
import io
import json
import re
import sys
import zipfile
from pathlib import Path

import numpy as np
import pandas as pd

sys.path.insert(0, "src")
sys.path.insert(0, str(Path(__file__).parent))
sys.path.insert(0, "remote/datasets")
from domain_adaptation.method import cusum, standardise
from safe_extract import check_member_names

ZIP = next(Path("/mnt/vault/datasets/femto").glob("*/raw/FEMTO_Bearing.zip"))
PER_DAY = 8640
HEALTHY_N, MARGIN = 720, 100
BASES = (60, 180, 360)
ACC = re.compile(r"^(Learning_set|Full_Test_Set)/(Bearing\d_\d)/acc_(\d+)\.csv$")


def records(cache: Path) -> pd.DataFrame:
    if cache.is_file():
        return pd.read_csv(cache)
    z = zipfile.ZipFile(ZIP)
    z2 = zipfile.ZipFile(io.BytesIO(z.read("10. FEMTO Bearing/FEMTOBearingDataSet.zip")))
    rows = []
    for inner in ("Training_set.zip", "Validation_Set.zip"):
        z3 = zipfile.ZipFile(io.BytesIO(z2.read(inner)))
        names = z3.namelist()
        check_member_names(names, Path(inner))
        for n in names:
            m = ACC.match(n)
            if not m:
                continue
            txt = z3.read(n).decode()
            sep = ";" if txt.count(";") > txt.count(",") else ","
            a = np.loadtxt(io.StringIO(txt), delimiter=sep)
            row = {"set": m[1], "bearing": m[2], "record": int(m[3])}
            for c, col in (("h", 4), ("v", 5)):
                x = a[:, col] - a[:, col].mean()
                rms = np.sqrt((x ** 2).mean())
                row[f"rms_{c}"], row[f"kurt_{c}"] = rms, (x ** 4).mean() / rms ** 4
            rows.append(row)
    df = pd.DataFrame(rows).sort_values(["bearing", "record"]).reset_index(drop=True)
    cache.parent.mkdir(parents=True, exist_ok=True)
    df.to_csv(cache, index=False)
    return df


def analyse(df: pd.DataFrame, ch: str) -> dict:
    out = {}
    for B in BASES:
        S = {}
        for b, g in df.groupby("bearing"):
            g = g.sort_values("record")
            for st in ("rms", "kurt"):
                v = np.log(g[f"{st}_{ch}"].to_numpy())
                S.setdefault(b, {})[st] = cusum(standardise(v, v[:B]), start=B)
            S[b]["n"] = len(g)
        longs = [b for b in S if S[b]["n"] >= B + HEALTHY_N + MARGIN]
        seg = slice(B, B + HEALTHY_N)
        res = {}
        for st in ("rms", "kurt"):
            det, events, healthy_records = {}, 0, 0
            for b in S:
                h = max(np.nanmax(S[o][st][seg]) for o in longs if o != b) + 1e-9
                c = S[b][st]
                start = B + HEALTHY_N if b in longs else B
                idx = np.flatnonzero(c[start:] > h)
                det[b] = float((S[b]["n"] - 1 - (idx[0] + start)) * 10 / 3600) if len(idx) else None
                if b in longs:
                    over = c[seg] > h
                    events += int(np.sum(over[1:] & ~over[:-1]) + over[0])
                    healthy_records += HEALTHY_N
            leads = [v for v in det.values() if v is not None]
            res[st] = {"detected": len(leads), "of": len(S), "median_lead_h": float(np.median(leads)) if leads else 0.0,
                       "fa_per_day": events / healthy_records * PER_DAY if healthy_records else float("nan"),
                       "n_long": len(longs), "lead_h": det}
        out[B] = res
    best = max(out[B]["rms"]["detected"] for B in BASES)
    ok = [B for B in BASES if out[B]["rms"]["fa_per_day"] <= 1 and out[B]["rms"]["detected"] >= best - 1]
    out["rule"] = {"baseline_records": ok[0] if ok else None,
                   "baseline_minutes": ok[0] * 10 / 60 if ok else None,
                   "achieved_fa_per_day": {B: out[B]["rms"]["fa_per_day"] for B in BASES}}
    out["rms_ge_kurt"] = all(out[B]["rms"]["detected"] >= out[B]["kurt"]["detected"] for B in BASES)
    return out


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", type=Path, default=Path("outputs/wp16"))
    a = ap.parse_args()
    df = records(a.out / "femto_records.csv.gz")
    allres = {ch: analyse(df, ch) for ch in ("h", "v")}
    L = ["# WP16: FEMTO/PRONOSTIA, long-baseline false alarms of the trigger (unseen)", "",
         f"Generated by `scripts/analysis/wp16_femto.py`; pre-registered in notes/26. {df.bearing.nunique()} bearings, "
         f"{len(df)} records (0.1 s every 10 s). CUSUM k=0.5, FA budget 0 leave-one-bearing-out; assumed-healthy = the "
         "720 records (2 h) after the baseline.", ""]
    for ch, r in allres.items():
        rule = r["rule"]
        L += [f"## {'horizontal (primary)' if ch == 'h' else 'vertical'}", "",
              f"**Baseline-duration rule:** " + (f"{rule['baseline_minutes']:.0f} min ({rule['baseline_records']} records)"
                                                 if rule["baseline_records"] else "no B reached <= 1 FA/day; achieved: " +
                                                 ", ".join(f"{B} rec -> {v:.1f}/day" for B, v in rule["achieved_fa_per_day"].items())),
              f"RMS detects >= kurtosis at every B: {r['rms_ge_kurt']}", "",
              "| baseline | statistic | detected | median lead (h) | held-out FA per day | bearings in FA estimate |", "|---|---|---|---|---|---|"]
        for B in BASES:
            for st in ("rms", "kurt"):
                x = r[B][st]
                L.append(f"| {B} rec ({B * 10 / 60:.0f} min) | {st} | {x['detected']}/{x['of']} | {x['median_lead_h']:.2f} | "
                         f"{x['fa_per_day']:.1f} | {x['n_long']} |")
        L.append("")
    md = "\n".join(L) + "\n"
    (a.out / "wp16_report.md").write_text(md)
    (a.out / "wp16_results.json").write_text(json.dumps({ch: {str(k): v for k, v in r.items()} for ch, r in allres.items()},
                                                        indent=1, default=float))
    print(md)


if __name__ == "__main__":
    main()
